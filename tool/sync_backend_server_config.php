<?php

// Export only public server addresses. Never copy the backend .env into the app.
$backend = $argv[1] ?? __DIR__.'/../../hr-ky-admin';
if (!is_file($backend.'/vendor/autoload.php') || !is_file($backend.'/.env')) {
    fwrite(STDERR, "Backend dependencies or .env not found. Pass the hr-ky-admin directory.\n");
    exit(1);
}
require $backend.'/vendor/autoload.php';
$values = Dotenv\Dotenv::createArrayBacked($backend)->load();
$app = require $backend.'/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();
config([
    'app.url' => $values['APP_URL'] ?? null,
    'app.mobile_app_url' => $values['MOBILE_APP_URL'] ?? null,
    'app.fallback_url' => $values['APP_FALLBACK_URL'] ?? null,
    'app.mobile_app_fallback_url' => $values['MOBILE_APP_FALLBACK_URL'] ?? null,
]);
$literal = static fn ($value) => str_replace('$', '\\$', json_encode($value, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR));
$primary = $literal(App\Helpers\MobileServerConfiguration::primaryUrl());
$backup = $literal(App\Helpers\MobileServerConfiguration::fallbackUrl());
$output = __DIR__.'/../lib/config/backend_server_defaults.dart';
if (!is_dir(dirname($output))) {
    mkdir(dirname($output), 0777, true);
}
file_put_contents($output, "// Generated by tool/sync_backend_server_config.php from backend .env.\n"
    ."// Contains public addresses only. Runtime backend settings take precedence.\n"
    ."class BackendServerDefaults {\n"
    ."  static const String primaryUrl = String.fromEnvironment(\n"
    ."    'KY_API_BASE_URL',\n"
    ."    defaultValue: $primary,\n"
    ."  );\n"
    ."  static const String? fallbackUrl = $backup;\n"
    ."}\n");
echo "Updated public server defaults from backend .env.\n";
